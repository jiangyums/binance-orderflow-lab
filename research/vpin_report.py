"""VPIN Evaluation Report + Walk-Forward Validation.

Generates data/hist/vpin/report.md with:
  1) Best FPR from sweep_results.csv (if exists)
  2) Rank IC / ICIR / Sharpe via research.metrics_ic on vpin_validity_multiday.npz
  3) Walk-forward: first 2/3 buckets IS threshold, last 1/3 OOS validation
  4) Markdown table: Metric | Value | Threshold | Verdict
"""
from pathlib import Path
import numpy as np
import pandas as pd


def _safe_load_sweep(data_dir: Path):
    csv = data_dir / "sweep_results.csv"
    if not csv.exists():
        return None, None
    try:
        df = pd.read_csv(csv)
        if df.empty or "fpr" not in df.columns:
            return df, None
        # Best = lowest FPR, tie-break higher precision then more events
        # Sort by fpr asc, precision desc
        sort_cols = ["fpr"]
        ascending = [True]
        if "precision" in df.columns:
            sort_cols.append("precision")
            ascending.append(False)
        best = df.sort_values(by=sort_cols, ascending=ascending).iloc[0]
        return df, best
    except Exception:
        return None, None


def _safe_load_npz(data_dir: Path):
    # Primary: vpin_validity_multiday.npz in data_dir
    candidates = [
        data_dir / "vpin_validity_multiday.npz",
        Path("data/hist/vpin/vpin_validity_multiday.npz"),
    ]
    for p in candidates:
        if p.exists():
            try:
                d = np.load(str(p), allow_pickle=True)
                return d, p
            except Exception:
                continue
    return None, None


def generate_report(data_dir="data/hist/vpin", out_path="data/hist/vpin/report.md"):
    data_dir = Path(data_dir)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines = []
    lines.append("# VPIN Evaluation Report")
    lines.append("")
    lines.append("> Auto-generated by `research/vpin_report.py` — Academic-standard evaluation per Wu et al. (2013) + Bambade (2018) + industry IC/ICIR/Sharpe/DSR framework.")
    lines.append("")

    # ------------------------------------------------------------------
    # 1) Sweep results
    # ------------------------------------------------------------------
    df_sweep, best = _safe_load_sweep(data_dir)
    lines.append("## 1. Parameter Sweep (Best FPR)")
    lines.append("")
    if best is not None:
        lines.append(f"- Source: `{data_dir / 'sweep_results.csv'}` — {len(df_sweep)} combos.")
        lines.append(f"- **Best FPR**: `{float(best['fpr']):.4f}` — precision `{float(best.get('precision', 0)):.4f}` — n_events `{int(best.get('n_events', 0))}`")
        # show best params
        param_cols = [c for c in ["bucket_volume", "vpin_window", "theta", "exit_q", "horizon", "price_mode"] if c in df_sweep.columns]
        if param_cols:
            param_str = ", ".join(f"{c}={best[c]}" for c in param_cols)
            lines.append(f"- Best params: `{param_str}`")
        # small table of top 5
        try:
            top5 = df_sweep.sort_values(by=["fpr", "precision"] if "precision" in df_sweep.columns else ["fpr"]).head(5)
            lines.append("")
            lines.append("Top 5 combos (lowest FPR):")
            lines.append("")
            lines.append(top5.to_markdown(index=False))
        except Exception:
            pass
    else:
        lines.append(f"- No `sweep_results.csv` found at `{data_dir / 'sweep_results.csv'}` — run `research/vpin_sweep.py` to populate.")
        lines.append("- Best FPR: **N/A (NEEDS_DATA)**")
    lines.append("")

    # ------------------------------------------------------------------
    # 2) Load NPZ and compute IC / ICIR / Sharpe
    # ------------------------------------------------------------------
    lines.append("## 2. Signal-Layer Metrics (Rank IC / ICIR / Sharpe)")
    lines.append("")
    npz, npz_path = _safe_load_npz(data_dir)

    # Placeholders for summary table
    summary_rows = []

    if npz is None:
        lines.append(f"- No `vpin_validity_multiday.npz` found (checked `{data_dir / 'vpin_validity_multiday.npz'}`).")
        lines.append("- Rank IC / ICIR / Sharpe: **N/A (NEEDS_DATA)**")
        lines.append("")
        summary_rows.append({"Metric": "Best FPR (sweep)", "Value": "N/A", "Threshold": "< 0.80", "Verdict": "NEEDS_DATA"})
        summary_rows.append({"Metric": "Rank IC (5m)", "Value": "N/A", "Threshold": "> 0.05", "Verdict": "NEEDS_DATA"})
        summary_rows.append({"Metric": "ICIR (5m)", "Value": "N/A", "Threshold": "> 0.50", "Verdict": "NEEDS_DATA"})
        summary_rows.append({"Metric": "Sharpe (fwd 5m)", "Value": "N/A", "Threshold": "> 1.00", "Verdict": "NEEDS_DATA"})
    else:
        lines.append(f"- Source: `{npz_path}`")
        try:
            vpin_all = np.asarray(npz["vpin_all"], dtype=float)
            bucket_kline_idx = np.asarray(npz["bucket_kline_idx"], dtype=int)
            kline_prices = np.asarray(npz["kline_prices"], dtype=float)
        except Exception as e:
            lines.append(f"- Failed to parse NPZ fields: {e}")
            vpin_all = np.array([])
            bucket_kline_idx = np.array([])
            kline_prices = np.array([])

        # Import metrics lazily to avoid hard failure if scipy missing
        try:
            from research.metrics_ic import rank_ic, icir, sharpe_ratio, sortino_ratio
            has_metrics = True
        except Exception as e:
            lines.append(f"- `research.metrics_ic` import failed: {e}")
            has_metrics = False
            rank_ic = icir = sharpe_ratio = sortino_ratio = None

        horizons = [5, 15, 30, 60, 120]
        ic_by_h = {}
        icir_by_h = {}
        sharpe_by_h = {}
        sortino_by_h = {}

        if has_metrics and len(vpin_all) > 10 and len(kline_prices) > 10:
            lines.append("")
            lines.append(f"- Buckets: {len(vpin_all)} (valid {int(np.isfinite(vpin_all).sum())}), klines: {len(kline_prices)}")
            lines.append("")
            lines.append("| Horizon | Rank IC | ICIR | Sharpe(fwd) | Sortino(fwd) | n | Verdict |")
            lines.append("|---|---:|---:|---:|---:|---:|---|")
            for h in horizons:
                try:
                    fwd_idx = np.clip(bucket_kline_idx + h, 0, len(kline_prices) - 1)
                    # forward log return at bucket granularity
                    rets = np.log(kline_prices[fwd_idx] / kline_prices[bucket_kline_idx])
                    # align mask
                    mask = np.isfinite(vpin_all) & np.isfinite(rets)
                    n = int(mask.sum())
                    if n < 10:
                        ic = np.nan
                        icir_v = np.nan
                        sr = np.nan
                        sor = np.nan
                    else:
                        ic = rank_ic(vpin_all[mask], np.abs(rets[mask]))  # vol IC is primary for VPIN
                        # ICIR: split into 5 chronological chunks and compute IC per chunk
                        chunks = 5
                        chunk_size = n // chunks
                        ic_series = []
                        v = vpin_all[mask]
                        r = np.abs(rets[mask])
                        for c in range(chunks):
                            s = c * chunk_size
                            e = (c + 1) * chunk_size if c < chunks - 1 else n
                            if e - s < 10:
                                continue
                            try:
                                ic_c = rank_ic(v[s:e], r[s:e])
                                if np.isfinite(ic_c):
                                    ic_series.append(ic_c)
                            except Exception:
                                continue
                        icir_v = icir(np.array(ic_series)) if len(ic_series) >= 3 else np.nan
                        sr = sharpe_ratio(rets[mask])
                        sor = sortino_ratio(rets[mask])
                    ic_by_h[h] = ic
                    icir_by_h[h] = icir_v
                    sharpe_by_h[h] = sr
                    sortino_by_h[h] = sor
                    # verdict: IC >0.05 positive, ICIR >0.5 stable, else FAIL
                    ic_ok = np.isfinite(ic) and ic > 0.05
                    icir_ok = np.isfinite(icir_v) and icir_v > 0.5
                    verdict = "PASS" if (ic_ok and icir_ok) else ("WEAK" if (np.isfinite(ic) and ic > 0.02) else "FAIL")
                    lines.append(f"| {h:3d}m | {ic:+.4f} | {icir_v:.2f} | {sr:.2f} | {sor:.2f} | {n} | {verdict} |")
                except Exception as e:
                    lines.append(f"| {h:3d}m | err | err | err | err | 0 | FAIL |  <!-- {e} -->")
            lines.append("")
            # Also echo precomputed corrs from NPZ for reference
            try:
                ref_parts = []
                for h in horizons:
                    k = f"corr_abs_{h}m"
                    if k in npz.files:
                        ref_parts.append(f"{h}m={float(npz[k]):+.3f}")
                if ref_parts:
                    lines.append(f"- Precomputed corr(|ret|,VPIN) from NPZ: {', '.join(ref_parts)}")
                    lines.append("")
            except Exception:
                pass

            # Summary rows for Metric | Value | Threshold | Verdict table
            # Best FPR
            if best is not None:
                best_fpr = float(best["fpr"])
                verdict_fpr = "PASS" if best_fpr < 0.70 else ("WEAK" if best_fpr < 0.85 else "FAIL")
                summary_rows.append({"Metric": "Best FPR (sweep)", "Value": f"{best_fpr:.4f}", "Threshold": "< 0.70", "Verdict": verdict_fpr})
            else:
                summary_rows.append({"Metric": "Best FPR (sweep)", "Value": "N/A", "Threshold": "< 0.70", "Verdict": "NEEDS_DATA"})

            # Rank IC 5m
            ic5 = ic_by_h.get(5, np.nan)
            if np.isfinite(ic5):
                v = "PASS" if ic5 > 0.05 else ("WEAK" if ic5 > 0.02 else "FAIL")
                summary_rows.append({"Metric": "Rank IC (|ret|, VPIN) 5m", "Value": f"{ic5:+.4f}", "Threshold": "> 0.05", "Verdict": v})
            else:
                summary_rows.append({"Metric": "Rank IC (|ret|, VPIN) 5m", "Value": "N/A", "Threshold": "> 0.05", "Verdict": "NEEDS_DATA"})

            icir5 = icir_by_h.get(5, np.nan)
            if np.isfinite(icir5):
                v = "PASS" if icir5 > 0.50 else ("WEAK" if icir5 > 0.20 else "FAIL")
                summary_rows.append({"Metric": "ICIR (5m, 5 chunks)", "Value": f"{icir5:.2f}", "Threshold": "> 0.50", "Verdict": v})
            else:
                summary_rows.append({"Metric": "ICIR (5m, 5 chunks)", "Value": "N/A", "Threshold": "> 0.50", "Verdict": "NEEDS_DATA"})

            s5 = sharpe_by_h.get(5, np.nan)
            if np.isfinite(s5):
                # Sharpe of raw fwd returns is not VPIN strategy sharpe; threshold relaxed
                v = "PASS" if s5 > 1.0 else ("WEAK" if s5 > 0.0 else "FAIL")
                summary_rows.append({"Metric": "Sharpe (fwd 5m raw)", "Value": f"{s5:.2f}", "Threshold": "> 1.00", "Verdict": v + " (raw, not strategy)"})
            else:
                summary_rows.append({"Metric": "Sharpe (fwd 5m raw)", "Value": "N/A", "Threshold": "> 1.00", "Verdict": "NEEDS_DATA"})

            # Also add 30m IC
            ic30 = ic_by_h.get(30, np.nan)
            if np.isfinite(ic30):
                v = "PASS" if ic30 > 0.05 else ("WEAK" if ic30 > 0.02 else "FAIL")
                summary_rows.append({"Metric": "Rank IC (|ret|, VPIN) 30m", "Value": f"{ic30:+.4f}", "Threshold": "> 0.05", "Verdict": v})
            else:
                summary_rows.append({"Metric": "Rank IC (|ret|, VPIN) 30m", "Value": "N/A", "Threshold": "> 0.05", "Verdict": "NEEDS_DATA"})
        else:
            lines.append("- Insufficient data to compute IC series.")
            lines.append("")
            summary_rows.append({"Metric": "Best FPR (sweep)", "Value": "N/A", "Threshold": "< 0.70", "Verdict": "NEEDS_DATA"})

    # ------------------------------------------------------------------
    # 3) Walk-Forward validation
    # ------------------------------------------------------------------
    lines.append("## 3. Walk-Forward Validation (2/3 IS → 1/3 OOS)")
    lines.append("")
    lines.append("- Split: first 2/3 buckets = in-sample (IS) for threshold calibration, last 1/3 = out-of-sample (OOS).")
    lines.append("")

    if npz is None:
        lines.append("- Skipped — NPZ missing.")
        lines.append("")
        summary_rows.append({"Metric": "WF IC decay (OOS/IS 5m)", "Value": "N/A", "Threshold": "> 0.50", "Verdict": "NEEDS_DATA"})
        summary_rows.append({"Metric": "WF vol ratio OOS (P90 high/low)", "Value": "N/A", "Threshold": "> 1.20", "Verdict": "NEEDS_DATA"})
    else:
        try:
            vpin_all = np.asarray(npz["vpin_all"], dtype=float)
            bucket_kline_idx = np.asarray(npz["bucket_kline_idx"], dtype=int)
            kline_prices = np.asarray(npz["kline_prices"], dtype=float)
            n = len(vpin_all)
            n_train = int(n * 2 / 3)
            if n_train < 20 or n - n_train < 20:
                lines.append(f"- Too few buckets for WF split: n={n}, train={n_train}, test={n-n_train}.")
                lines.append("")
            else:
                vpin_is = vpin_all[:n_train]
                vpin_oos = vpin_all[n_train:]
                idx_is = bucket_kline_idx[:n_train]
                idx_oos = bucket_kline_idx[n_train:]

                # IS threshold: P90 of valid VPIN in IS
                valid_is = vpin_is[np.isfinite(vpin_is)]
                p90_is = float(np.percentile(valid_is, 90)) if len(valid_is) > 10 else np.nan
                p50_is = float(np.percentile(valid_is, 50)) if len(valid_is) > 10 else np.nan
                lines.append(f"- IS P50={p50_is:.4f}, P90 threshold={p90_is:.4f} (from {len(valid_is)} valid IS buckets).")
                lines.append("")

                from research.metrics_ic import rank_ic as _rank_ic

                # Walk-forward IC decay per horizon
                lines.append("| Horizon | IC_IS | IC_OOS | Decay (OOS/IS) | Verdict |")
                lines.append("|---|---:|---:|---:|---|")
                wf_decays = []
                for h in [5, 30, 60]:
                    try:
                        fwd_is = np.clip(idx_is + h, 0, len(kline_prices) - 1)
                        rets_is = np.log(kline_prices[fwd_is] / kline_prices[idx_is])
                        mask_is = np.isfinite(vpin_is) & np.isfinite(rets_is)
                        fwd_oos = np.clip(idx_oos + h, 0, len(kline_prices) - 1)
                        rets_oos = np.log(kline_prices[fwd_oos] / kline_prices[idx_oos])
                        mask_oos = np.isfinite(vpin_oos) & np.isfinite(rets_oos)
                        if mask_is.sum() < 10 or mask_oos.sum() < 10:
                            ic_is = ic_oos = np.nan
                            decay = np.nan
                        else:
                            ic_is = _rank_ic(vpin_is[mask_is], np.abs(rets_is[mask_is]))
                            ic_oos = _rank_ic(vpin_oos[mask_oos], np.abs(rets_oos[mask_oos]))
                            decay = float(ic_oos / ic_is) if np.isfinite(ic_is) and abs(ic_is) > 1e-9 else np.nan
                        verdict = "PASS" if np.isfinite(decay) and decay > 0.5 else ("WEAK" if np.isfinite(decay) and decay > 0.0 else "FAIL")
                        wf_decays.append(decay)
                        lines.append(f"| {h:3d}m | {ic_is:+.4f} | {ic_oos:+.4f} | {decay:.2f} | {verdict} |")
                    except Exception as e:
                        lines.append(f"| {h:3d}m | err | err | err | FAIL |  <!-- {e} -->")

                lines.append("")

                # Walk-forward vol ratio OOS using IS threshold
                try:
                    # Use 5m horizon for vol ratio as simplest
                    h = 5
                    fwd_oos = np.clip(idx_oos + h, 0, len(kline_prices) - 1)
                    rets_oos = np.log(kline_prices[fwd_oos] / kline_prices[idx_oos])
                    mask_oos = np.isfinite(vpin_oos) & np.isfinite(rets_oos)
                    v = vpin_oos[mask_oos]
                    r = np.abs(rets_oos[mask_oos])
                    high_m = v >= p90_is
                    low_m = v <= np.percentile(valid_is, 10) if len(valid_is) > 10 else v <= np.median(v)
                    high_vol = float(np.mean(r[high_m])) if high_m.sum() > 5 else np.nan
                    low_vol = float(np.mean(r[low_m])) if low_m.sum() > 5 else np.nan
                    vol_ratio = float(high_vol / low_vol) if np.isfinite(high_vol) and np.isfinite(low_vol) and low_vol > 0 else np.nan
                    lines.append(f"- OOS vol ratio (P90 high vs P10 low, 5m): high={high_vol:.6f} low={low_vol:.6f} ratio={vol_ratio:.3f}")
                    lines.append(f"  - High VPIN buckets OOS: {int(high_m.sum())}, Low: {int(low_m.sum())}")
                    lines.append("")
                    # OOS event-style check: does high VPIN predict higher realized vol?
                    vr_verdict = "PASS" if np.isfinite(vol_ratio) and vol_ratio > 1.2 else ("WEAK" if np.isfinite(vol_ratio) and vol_ratio > 1.0 else "FAIL")
                    summary_rows.append({"Metric": "WF IC decay (OOS/IS 5m)", "Value": f"{wf_decays[0]:.2f}" if len(wf_decays) > 0 and np.isfinite(wf_decays[0]) else "N/A", "Threshold": "> 0.50", "Verdict": ("PASS" if len(wf_decays)>0 and np.isfinite(wf_decays[0]) and wf_decays[0] > 0.5 else "FAIL" if len(wf_decays)>0 and np.isfinite(wf_decays[0]) else "NEEDS_DATA")})
                    summary_rows.append({"Metric": "WF vol ratio OOS (P90 high/low, 5m)", "Value": f"{vol_ratio:.3f}" if np.isfinite(vol_ratio) else "N/A", "Threshold": "> 1.20", "Verdict": vr_verdict})
                except Exception as e:
                    lines.append(f"- WF vol ratio failed: {e}")
                    lines.append("")
                    summary_rows.append({"Metric": "WF IC decay (OOS/IS 5m)", "Value": "N/A", "Threshold": "> 0.50", "Verdict": "NEEDS_DATA"})
                    summary_rows.append({"Metric": "WF vol ratio OOS", "Value": "N/A", "Threshold": "> 1.20", "Verdict": "NEEDS_DATA"})

                # Additional: naive baseline comparison via vpin_prediction_quality if MIR available
                # We do not have MIR in NPZ, so we skip FPR WF and note it
                lines.append("- Note: WF FPR/Precision requires MIR time series; not in NPZ. Run `vpin_prediction_quality.py` for event-based WF.")
                lines.append("")
        except Exception as e:
            lines.append(f"- Walk-forward failed: {e}")
            lines.append("")
            summary_rows.append({"Metric": "WF IC decay (OOS/IS 5m)", "Value": "N/A", "Threshold": "> 0.50", "Verdict": "NEEDS_DATA"})

    # ------------------------------------------------------------------
    # 4) Summary verdict table: Metric | Value | Threshold | Verdict
    # ------------------------------------------------------------------
    lines.append("## 4. Summary Verdict")
    lines.append("")
    lines.append("| Metric | Value | Threshold | Verdict |")
    lines.append("|---|---:|---|---|")
    if not summary_rows:
        # fallback minimal
        summary_rows = [{"Metric": "Best FPR", "Value": "N/A", "Threshold": "TBD", "Verdict": "NEEDS_DATA"}]
    for r in summary_rows:
        # escape pipe in metric
        metric = str(r["Metric"]).replace("|", "/")
        lines.append(f"| {metric} | {r['Value']} | {r['Threshold']} | {r['Verdict']} |")
    lines.append("")

    # Overall verdict
    fails = sum(1 for r in summary_rows if r["Verdict"] == "FAIL")
    passes = sum(1 for r in summary_rows if r["Verdict"] == "PASS")
    needs = sum(1 for r in summary_rows if "NEEDS_DATA" in r["Verdict"])
    if needs > 0 and passes == 0 and fails == 0:
        overall = "NEEDS_DATA — insufficient artifacts (run vpin_sweep + vpin_validity)"
    elif fails >= 2:
        overall = "FAIL — VPIN not effective as standalone signal for BTCUSDT (consistent with FPR ~96% early findings)"
    elif fails == 1 and passes >= 1:
        overall = "WEAK — marginal signal, may require regime conditioning"
    elif passes >= 2:
        overall = "PASS — VPIN shows predictive value"
    else:
        overall = "WEAK/NEEDS_DATA — inconclusive"

    lines.append(f"**Overall**: {overall}")
    lines.append("")
    lines.append("---")
    lines.append(f"*Generated: data_dir=`{data_dir}`, out_path=`{out_path}`*")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    return str(out_path)
